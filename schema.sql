CREATE VIEW v_resumen_proveedores AS 
            SELECT CLIENTE AS cod_proveedor, CLIEDENO AS nombre, CUIT,
                COUNT(*) AS cant_facturas,
                MIN(FECHA) AS primera_factura, MAX(FECHA) AS ultima_factura,
                ROUND(SUM(TOTAL_A), 2) AS total_comprado,
                ROUND(AVG(TOTAL_A), 2) AS ticket_promedio
            FROM proveedores_facturas
            WHERE CLIENTE IS NOT NULL AND CLIENTE != ''
            GROUP BY CLIENTE, CLIEDENO, CUIT
            ORDER BY total_comprado DESC;